"""Builds scripts/names/name_lists.gd from scripts/names/names.txt.

python scripts/dev/build_names.py
Prints each list's size; every list should hold at least 100 unique names.
"""
import pathlib, re

ROOT = pathlib.Path(__file__).resolve().parents[2]
src = (ROOT / "scripts/names/names.txt").read_text(encoding="utf-8")
lists, key = {}, None
for line in src.splitlines():
    line = line.strip()
    if not line or line.startswith("# "):
        continue
    if line.startswith("## "):
        sp, sex = line[3:].split()
        key = f"{sp}:{sex}"
        lists[key] = []
        continue
    for name in line.split(","):
        name = name.strip()
        if name and name not in lists[key]:
            lists[key].append(name)
out = ["# Generated by scripts/dev/build_names.py from names.txt; edit that file.",
       "class_name NameLists", "extends RefCounted", "", "const LISTS: Dictionary = {"]
for k, names in lists.items():
    quoted = ", ".join('"%s"' % n.replace('"', '\\"') for n in names)
    out.append(f'\t"{k}": [{quoted}],')
    print(f"{k:16} {len(names)}")
out.append("}")
(ROOT / "scripts/names/name_lists.gd").write_text("\n".join(out) + "\n", encoding="utf-8")
