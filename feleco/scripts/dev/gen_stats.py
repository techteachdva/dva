"""Write scripts/ui/game_stats.gd: code size and shipped build size.

python scripts/dev/gen_stats.py [web build dir]
Run before exporting; run again after to record the real build size.
"""
import pathlib, sys, datetime

ROOT = pathlib.Path(__file__).resolve().parents[2]
BUILD = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "exports" / "web-safe"
OUT = ROOT / "scripts" / "ui" / "game_stats.gd"

def counted(p):
    rel = p.relative_to(ROOT).as_posix()
    return not (rel.startswith("scripts/dev/") or rel.startswith("exports/") or rel.startswith(".godot/") or p == OUT)

files = [p for ext in ("*.gd", "*.gdshader", "*.tscn") for p in ROOT.rglob(ext) if counted(p)]
code = [p for p in files if p.suffix in (".gd", ".gdshader")]
lines = sum(sum(1 for l in p.read_text(encoding="utf-8", errors="replace").splitlines() if l.strip()) for p in code)
src_bytes = sum(p.stat().st_size for p in files)
build = [p for p in BUILD.glob("Feleco.*") if p.suffix in (".pck", ".wasm", ".js", ".html")]
build_bytes = sum(p.stat().st_size for p in build)

OUT.write_text(f'''class_name GameStats
extends RefCounted

# Generated by scripts/dev/gen_stats.py before each release. Do not edit.
const CODE_LINES: int = {lines}
const CODE_FILES: int = {len(code)}
const SCENE_FILES: int = {len(files) - len(code)}
const SOURCE_BYTES: int = {src_bytes}
const BUILD_BYTES: int = {build_bytes}
const STAMP: String = "{datetime.date.today().isoformat()}"
''', encoding="utf-8")
print(f"lines={lines} code_files={len(code)} source={src_bytes} build={build_bytes}")
