/**
 * Builds CyberMorph's "NOT A WORD" Rotlings (src/site/cybermorph/js/data/nonwords.js).
 *
 * For every real word the game knows, swap one piece for another piece of the same type and
 * origin, and keep the result only if a full English word list (an-array-of-english-words,
 * a devDependency; nothing of it ships) says it is not a word AND it is not one letter away
 * from a real word (that would read as a misspelling, which is a different Rotling).
 *
 *   node scripts/build-cybermorph-nonwords.mjs
 */
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';

const require = createRequire(import.meta.url);
const ENGLISH = new Set(require('an-array-of-english-words'));
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../src/site/cybermorph/js');
const imp = (p) => import(pathToFileURL(path.join(ROOT, p)).href);
const { MORPHEMES, morph } = await imp('data/morphemes.js');
const { build } = await imp('compiler/wordsum.js');
const { DICTIONARY, collectPartWords } = await imp('data/world.js');
const allWords = collectPartWords; // not waves.js: it imports the file this script writes

const PER_WORD = 3;
const INFLECTIONS = new Set(['s', 'es', 'ed', 'ing', 'est']);
const letters = 'abcdefghijklmnopqrstuvwxyz';
const real = (w) => ENGLISH.has(w) || DICTIONARY.has(w);

/** One deletion, insertion or substitution from a real word reads as a misspelling. */
function nearReal(w) {
  for (let i = 0; i <= w.length; i++) {
    if (i < w.length && real(w.slice(0, i) + w.slice(i + 1))) return true;
    for (const ch of letters) {
      if (real(w.slice(0, i) + ch + w.slice(i))) return true;
      if (i < w.length && ch !== w[i] && real(w.slice(0, i) + ch + w.slice(i + 1))) return true;
    }
  }
  return false;
}

// Deterministic shuffle so the file is stable between runs.
let seed = 12345;
const rnd = () => { seed = (seed * 1664525 + 1013904223) >>> 0; return seed / 4294967296; };
const shuffle = (a) => { const b = [...a]; for (let i = b.length - 1; i > 0; i--) { const j = Math.floor(rnd() * (i + 1)); [b[i], b[j]] = [b[j], b[i]]; } return b; };

const out = {};
let total = 0;
for (const w of allWords()) {
  const ids = w.ids;
  if (ids.some((id) => !MORPHEMES[id] || morph(id).type === 'word')) continue;
  const found = [];
  for (const i of shuffle(ids.map((_, k) => k))) {
    const m = morph(ids[i]);
    if (m.type === 'link' || INFLECTIONS.has(m.text)) continue;
    const swaps = shuffle(Object.keys(MORPHEMES).filter((x) => x !== ids[i] && MORPHEMES[x].type === m.type && MORPHEMES[x].origin === m.origin
      && MORPHEMES[x].text.length >= 2 && MORPHEMES[x].text !== m.text && MORPHEMES[x].meaning !== m.meaning && !INFLECTIONS.has(MORPHEMES[x].text)));
    for (const x of swaps) {
      if (found.length >= PER_WORD) break;
      const nids = ids.map((id, k) => (k === i ? x : id));
      let r;
      try { r = build(nids); } catch { continue; }
      const texts = nids.map((id) => morph(id).text);
      // A tripled letter (fallly) reads as a typo, not a made-up word.
      if (r.steps.length || texts.join('') !== r.word || r.word.length < 5 || /(.)\1\1/.test(r.word)) continue;
      if (real(r.word) || nearReal(r.word) || found.some((f) => f.show === r.word)) continue;
      found.push({ p: nids, show: r.word, swap: i });
    }
    if (found.length >= PER_WORD) break;
  }
  if (found.length) { out[w.word] = found; total += found.length; }
}

const body = `/**
 * "NOT A WORD" Rotlings. GENERATED by scripts/build-cybermorph-nonwords.mjs: each real word maps to
 * made-up words built from the same pieces with one swapped (\`swap\` is its index), checked against
 * a full English word list so none of them is a real word or one letter away from one.
 */

export const NONWORDS = ${JSON.stringify(out)};
`;
writeFileSync(path.join(ROOT, 'data/nonwords.js'), body);
console.log(`wrote js/data/nonwords.js: ${total} made-up words for ${Object.keys(out).length} real words`);
