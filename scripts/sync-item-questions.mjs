/**
 * Sync Tech Escape question bank → ITEM Diagnostic format.
 * Run: node scripts/sync-item-questions.mjs
 */
import fs from "fs";
import path from "path";
import { fileURLToPath, pathToFileURL } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
const questionsPath = path.join(root, "src/site/tech-escape/js/data/questions.js");
const outPath = path.join(root, "src/site/scripts/item-diagnostic-bank.js");

const mod = await import(pathToFileURL(questionsPath).href);
const { ALL_QUESTIONS } = mod;

function topicFromId(id) {
  if (id.startsWith("DES-")) return "design";
  if (id.startsWith("SYS-")) return "systems";
  if (id.startsWith("DAT-")) return "data";
  if (id.startsWith("COD-")) return "code";
  return "general";
}

function parseStd(std) {
  const m = String(std || "").match(/ITEM\s+([\d.]+)/);
  return m ? m[1] : "";
}

const converted = ALL_QUESTIONS.map((q) => ({
  id: q.id,
  std: parseStd(q.std),
  stdLabel: String(q.std || "").split("|")[0].replace(/^ITEM\s+[\d.]+\s*-\s*/, "").trim(),
  topic: topicFromId(q.id),
  q: q.q,
  a: q.a,
  correct: q.correct,
  why: q.why,
  level: q.level ?? 2,
}));

const header = `/**
 * AUTO-GENERATED by scripts/sync-item-questions.mjs
 * Source: src/site/tech-escape/js/data/questions.js (${converted.length} questions)
 * Do not edit by hand — run: npm run sync:item-questions
 */
(() => {
  "use strict";
  window.ITEMDiagnosticBank = ${JSON.stringify(converted, null, 2)};
})();
`;

fs.writeFileSync(outPath, header, "utf8");
console.log(`Wrote ${converted.length} questions to ${path.relative(root, outPath)}`);
