/**
 * Build writeflow-mn-ela-standards-data.js from CSV.
 * Usage: node scripts/build-mn-ela-standards.mjs
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const csvPath = path.join(root, "src/site/scripts/data/mn-ela-standards.csv");
const outPath = path.join(root, "src/site/scripts/writeflow-mn-ela-standards-data.js");

function parseCsv(text) {
  const rows = [];
  let i = 0;
  const len = text.length;
  const headers = [];

  function readField() {
    let field = "";
    if (text[i] === '"') {
      i += 1;
      while (i < len) {
        if (text[i] === '"') {
          if (text[i + 1] === '"') {
            field += '"';
            i += 2;
          } else {
            i += 1;
            break;
          }
        } else {
          field += text[i];
          i += 1;
        }
      }
      if (text[i] === ",") i += 1;
      return field;
    }
    while (i < len && text[i] !== "," && text[i] !== "\n" && text[i] !== "\r") {
      field += text[i];
      i += 1;
    }
    if (text[i] === ",") i += 1;
    return field;
  }

  while (i < len && text[i] !== "\n" && text[i] !== "\r") {
    headers.push(readField().trim());
    if (text[i] === "\r") i += 1;
    if (text[i] === "\n") i += 1;
  }
  if (text[i] === "\r") i += 1;
  if (text[i] === "\n") i += 1;

  while (i < len) {
    if (text[i] === "\r" || text[i] === "\n") {
      i += 1;
      continue;
    }
    const row = {};
    for (let h = 0; h < headers.length; h += 1) {
      row[headers[h]] = readField().trim();
    }
    while (i < len && (text[i] === "\r" || text[i] === "\n")) i += 1;
    if (Object.values(row).some((v) => v)) rows.push(row);
  }
  return rows;
}

function shortTitle(benchmark = "") {
  const line = String(benchmark).split("\n")[0].trim();
  return line.length > 72 ? `${line.slice(0, 69)}…` : line;
}

const csvText = fs.readFileSync(csvPath, "utf8");
const parsed = parseCsv(csvText);
const standards = [];

for (const row of parsed) {
  const code = String(row.Code || "").trim();
  const grade = Number(row.Grade);
  const benchmark = String(row.Benchmark || "").trim();
  if (!code || !grade || /end of/i.test(code)) continue;
  if (/^no benchmark/i.test(benchmark)) continue;

  standards.push({
    code,
    grade,
    strand: String(row.Strand || "").trim(),
    anchorStandard: String(row["Anchor Standard"] || "").trim(),
    benchmark,
    connections: "",
    shortTitle: shortTitle(benchmark),
    catalog: "mn_ela",
  });
}

const out = `/**
 * MN ELA standards grades 5–8 — generated by scripts/build-mn-ela-standards.mjs
 * Do not edit by hand; update src/site/scripts/data/mn-ela-standards.csv instead.
 */
window.WriteFlowMnElaStandardsData = ${JSON.stringify(standards, null, 2)};
`;

fs.writeFileSync(outPath, out, "utf8");
console.log(`Wrote ${standards.length} MN ELA standards to ${outPath}`);
